// 35 weeks curriculum titles generator for selection
export const CURRICULUM_WEEKS = Array.from({ length: 35 }, (_, idx) => {
  const weekNum = idx + 1;
  let term = weekNum <= 18 ? 'Học kỳ I' : 'Học kỳ II';
  let defaultSubject = weekNum % 3 === 1 ? 'Toán' : weekNum % 3 === 2 ? 'Tiếng Việt' : 'Khoa học';
  return {
    week: weekNum,
    term,
    subject: defaultSubject,
    title: `Tuần ${weekNum}: Ôn luyện chủ đề & Bài tập tuần ${weekNum}`,
  };
});
